import {writeFileSync} from 'node:fs';
import {SCENE,FONT} from '../src/pet-scene.js';
const colors=Object.entries(SCENE).map(([k,v])=>`#define SCENE_${k} ${v}u`).join('\n');
const letters=Object.keys(FONT).join(''),glyphs=Object.values(FONT).map(rows=>'{'+rows.join(',')+'}').join(',');
writeFileSync('firmware/v2/src/pet_scene.h',`// Generated by scripts/build-scene.mjs; code-drawn scene, original bitmap glyphs.
#pragma once
#include <string.h>
${colors}
static const char scene_letters[]="${letters}";
static const uint8_t scene_glyphs[][7]={${glyphs}};
static bool text_pixel(const char *text,int x,int y){
 if(x<0||y<0||y>=7||x%6>=5||(unsigned)(x/6)>=strlen(text))return false;
 const char *p=strchr(scene_letters,text[x/6]);return p&&(scene_glyphs[p-scene_letters][y]&(1u<<(4-x%6)));
}
static uint16_t scene_pixel(int x,int y){
 uint16_t c=y>=106?SCENE_grass:y>=102?SCENE_grassLight:SCENE_sky;
 if((x>=7&&x<26&&y>=39&&y<42)||(x>=12&&x<22&&y>=36&&y<39)||(x>=104&&x<123&&y>=49&&y<52)||(x>=109&&x<119&&y>=46&&y<49))c=SCENE_cloud;
 static const int points[][2]={{7,103},{21,106},{109,105},{121,102},{14,119},{44,124},{84,119},{113,125}};
 for(unsigned i=0;i<8;i++){int dx=x-points[i][0],dy=y-points[i][1];if((dx==0&&dy>=-4&&dy<=0)||(dx==-2&&dy>=-2&&dy<=-1)||(dx==2&&dy>=-3&&dy<=-1)||((dx==1||dx==-1)&&dy==0))c=SCENE_grassDark;}
 return c;
}
static int32_t overlay_pixel(int x,int y,const char *level,uint32_t xp,uint8_t hp,uint8_t action,uint32_t elapsed,bool max_level){
 if(text_pixel(level,x-4,y-5))return SCENE_text;
 if(text_pixel("HP",x-4,y-17))return hp<=25?SCENE_hungry:SCENE_text;
 unsigned experience=max_level?200:xp%200;
 if(x>=31&&x<124&&y>=6&&y<11)return x<(int)(31+experience*93/200)?SCENE_xp:SCENE_track;
 if(x>=31&&x<124&&y>=18&&y<23)return x<(int)(31+hp*93/100)?(hp<=25?SCENE_hungry:SCENE_hp):SCENE_track;
 if(action==3){unsigned phase=(elapsed/750)%4,rise=(elapsed%750)/250;for(unsigned i=0;i<=phase;i++)if(text_pixel("z",x-(81+(int)i*12),y-(61-(int)i*8-(int)rise)))return SCENE_text;}
 return -1;
}
`);
