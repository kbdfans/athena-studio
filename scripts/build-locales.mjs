import {readFileSync,writeFileSync} from 'node:fs';
const locales=['en','zh-TW','ja','ko','de','fr','es'],messages={};
for(const line of readFileSync('src/locales/ui.txt','utf8').split('\n')){
 if(!line.trim()||line.startsWith('#'))continue;
 const [key,...values]=line.split('|');if(values.length!==7)throw Error('Invalid locale row: '+key);
 if(messages[key])throw Error('Duplicate locale: '+key);
 messages[key]=Object.fromEntries(locales.map((l,i)=>[l,values[i]]));
}
for(const line of readFileSync('src/locales/help-en.txt','utf8').split('\n')){
 if(!line.trim())continue;const [key,en]=line.split('|');if(!en)throw Error(key);messages[key]??={};messages[key].en=en;
}
writeFileSync('src/locales/messages.js','// Generated by scripts/build-locales.mjs. Advanced help falls back to English.\nexport const MESSAGES='+JSON.stringify(messages,null,2)+';\n');
console.log(Object.keys(messages).length+' UI messages');
