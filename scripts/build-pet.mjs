import {writeFileSync,mkdirSync} from 'node:fs';
import {createPetPack} from '../src/pet-pack.js';
const pack=createPetPack('mint');
mkdirSync('public',{recursive:true});
writeFileSync('public/pixel-cat.pt40',pack);
const rows=Array.from({length:Math.ceil(pack.length/32)},(_,i)=>' '+Array.from(pack.slice(i*32,(i+1)*32)).join(','));
writeFileSync('firmware/v2/src/pet_default.h','// SPDX-License-Identifier: GPL-2.0-or-later\n// Generated by scripts/build-pet.mjs; original mint cat.\n#pragma once\nstatic const uint8_t pet_default['+pack.length+']={\n'+rows.join(',\n')+'\n};\n');
console.log(`Pet resource: ${pack.length} bytes (44 frames + 256-byte header).`);
